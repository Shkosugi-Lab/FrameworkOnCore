# Generates Designers.cs: the public types of .NET Framework 4.8's System.Design under System.Web.UI.Design,
# with their inheritance and no members. Controls name their designers ([Designer(typeof(...))]) and the
# runtime reads their attributes (TypeDescriptor.GetAttributes, the page compiler): the designer types
# must load. They never run in a deployed site.
# Run in Windows PowerShell (.NET Framework, which has System.Design):
#   powershell -File experiments\wf4c\shims\System.Design\generate.ps1
$ErrorActionPreference = 'Stop'
$assembly = [Reflection.Assembly]::Load('System.Design, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b03f5f7f11d50a3a')
$types = @($assembly.GetExportedTypes() | Where-Object { $_.Namespace -like 'System.Web.UI.Design*' -and -not $_.IsNested })
# And the base types they have in System.Design itself (ComponentDesigner), transitively.
for ($i = 0; $i -lt $types.Count; $i++) {
    $b = $types[$i].BaseType
    if ($b -and $b.IsGenericType) { $b = $b.GetGenericTypeDefinition() }
    if ($b -and $b.Assembly -eq $assembly -and $b.IsPublic -and $types -notcontains $b) { $types += $b }
}
$names = @{}; foreach ($t in $types) { $names[$t.FullName] = $true }

# A base type outside the generated set: kept if .NET has it (System.ComponentModel ...), otherwise none.
$available = @('System.Object', 'System.Attribute', 'System.EventArgs', 'System.ComponentModel.TypeConverter', 
    'System.ComponentModel.StringConverter', 'System.ComponentModel.ExpandableObjectConverter',
    'System.MulticastDelegate', 'System.Enum', 'System.ValueType', 'System.Exception')

function TypeName($t) {
    $n = $t.Name -replace '`\d+$', ''
    if ($t.IsGenericTypeDefinition) { $n += '<' + (($t.GetGenericArguments() | ForEach-Object { $_.Name }) -join ', ') + '>' }
    $n
}

$out = New-Object Text.StringBuilder
[void]$out.AppendLine('// Generated by generate.ps1 from .NET Framework 4.8''s System.Design (System.Web.UI.Design*): the types, their')
[void]$out.AppendLine('// inheritance, no members. Designers only have to load (controls name them in attributes).')
[void]$out.AppendLine('#pragma warning disable')
foreach ($group in ($types | Sort-Object Namespace, Name | Group-Object Namespace)) {
    [void]$out.AppendLine("namespace $($group.Name)")
    [void]$out.AppendLine('{')
    foreach ($t in $group.Group) {
        $name = TypeName $t
        if ($t.IsEnum) {
            $members = [Enum]::GetNames($t) | ForEach-Object { "$_ = $([Convert]::ToInt64([Enum]::Parse($t, $_)))" }
            [void]$out.AppendLine("    public enum $name : long { $($members -join ', ') }")
            continue
        }
        if ($t.IsInterface) { [void]$out.AppendLine("    public interface $name { }"); continue }
        if ($t.BaseType -and $t.BaseType.FullName -eq 'System.MulticastDelegate') {
            [void]$out.AppendLine("    public delegate void $name(object sender, System.EventArgs e);"); continue
        }
        $kind = if ($t.IsValueType) { 'struct' } else { 'class' }
        $modifiers = if ($t.IsValueType) { '' } elseif ($t.IsAbstract -and $t.IsSealed) { 'static ' } elseif ($t.IsAbstract) { 'abstract ' } elseif ($t.IsSealed) { 'sealed ' } else { '' }
        $base = ''
        if (-not $t.IsValueType -and $t.BaseType -and $t.BaseType.FullName -ne 'System.Object' -and -not ($t.IsAbstract -and $t.IsSealed)) {
            $b = $t.BaseType
            $bn = if ($b.IsGenericType) { $b.GetGenericTypeDefinition().FullName } else { $b.FullName }
            if ($names.ContainsKey($bn) -or $available -contains $bn) { $base = " : global::$($b.Namespace).$(TypeName $b)" }
        }
        [void]$out.AppendLine("    public $modifiers$kind $name$base { }")
    }
    [void]$out.AppendLine('}')
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'Designers.cs'), $out.ToString(), (New-Object Text.UTF8Encoding $false))
"$(@($types).Count) types"
