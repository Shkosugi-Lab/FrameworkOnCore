# Generates Core\Strings.generated.cs and Core\Error.generated.cs of the System.Data.Linq port
# (_upstream\src\WebFormsForCore.Data.Linq) from .NET Framework 4.8's own System.Data.Linq.dll, so that
# the port's messages and exception types are exactly .NET Framework's.
#
# referencesource has only part of the resource text (System.Data.Linq.txt covers the root namespace, and
# without the SqlClient's and Mapping's texts the sources' Strings.X / Error.X do not compile). The real
# assembly has it all: the resources give the format strings, reflection gives each member's shape, and
# invoking each Error method (with marker arguments) gives the exception type it creates.
#
# Windows only (loads the GAC assembly); run under Windows PowerShell 5.1 (.NET Framework). The output is
# committed with the port, so this runs only when regenerating.
$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSEdition -eq 'Core') { throw 'Run under Windows PowerShell 5.1 (needs .NET Framework to load the GAC assembly).' }

$assembly = [Reflection.Assembly]::Load('System.Data.Linq, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089')
$out = Join-Path $PSScriptRoot '_upstream\src\WebFormsForCore.Data.Linq\Core'
New-Item -ItemType Directory $out -Force | Out-Null

function Escape([string]$s) {
    $sb = New-Object Text.StringBuilder
    foreach ($c in $s.ToCharArray()) {
        switch ($c) {
            '"' { [void]$sb.Append('\"') }
            '\' { [void]$sb.Append('\\') }
            "`r" { [void]$sb.Append('\r') }
            "`n" { [void]$sb.Append('\n') }
            "`t" { [void]$sb.Append('\t') }
            default { if ([int]$c -lt 32) { [void]$sb.Append('\u{0:x4}' -f [int]$c) } else { [void]$sb.Append($c) } }
        }
    }
    $sb.ToString()
}

# C# type name for the parameter types the generated members mirror (object and string in practice).
function TypeName([type]$t) {
    switch ($t.FullName) {
        'System.Object' { 'object' } 'System.String' { 'string' } 'System.Int32' { 'int' } 'System.Boolean' { 'bool' }
        default { $t.FullName }
    }
}

$flags = [Reflection.BindingFlags]'Static,NonPublic,Public,DeclaredOnly'
$strings = New-Object Text.StringBuilder
$errors = New-Object Text.StringBuilder
$header = @"
// <auto-generated>
//     Generated by experiments/wf4c/generate-dlinq-resources.ps1 from .NET Framework 4.8's System.Data.Linq.dll
//     (the format strings from its resources, each Error method's exception type by invoking it), so that messages
//     and exception types are exactly .NET Framework's. Do not edit.
// </auto-generated>
using System;

"@
[void]$strings.Append($header)
[void]$errors.Append($header)

foreach ($ns in 'System.Data.Linq', 'System.Data.Linq.Mapping', 'System.Data.Linq.SqlClient') {
    $resources = @{}
    $reader = New-Object System.Resources.ResourceReader($assembly.GetManifestResourceStream("$ns.resources"))
    foreach ($entry in $reader) { $resources[$entry.Key] = $entry.Value }
    $reader.Close()

    $stringsType = $assembly.GetType("$ns.Strings")
    $errorType = $assembly.GetType("$ns.Error")

    # ---- Strings: a property per plain text, a method per format string ----
    [void]$strings.AppendLine("namespace $ns")
    [void]$strings.AppendLine('{')
    [void]$strings.AppendLine('    internal static partial class Strings')
    [void]$strings.AppendLine('    {')
    foreach ($p in ($stringsType.GetProperties($flags) | Sort-Object Name)) {
        if (-not $resources.ContainsKey($p.Name)) { throw "$ns.Strings.$($p.Name): no resource" }
        [void]$strings.AppendLine("        internal static string $($p.Name) => `"$(Escape $resources[$p.Name])`";")
    }
    foreach ($m in ($stringsType.GetMethods($flags) | Where-Object { -not $_.IsSpecialName } | Sort-Object Name)) {
        if (-not $resources.ContainsKey($m.Name)) { throw "$ns.Strings.$($m.Name): no resource" }
        $params = ($m.GetParameters() | ForEach-Object { "$(TypeName $_.ParameterType) $($_.Name)" }) -join ', '
        $args = ($m.GetParameters() | ForEach-Object { $_.Name }) -join ', '
        [void]$strings.AppendLine("        internal static string $($m.Name)($params) => string.Format(System.Globalization.CultureInfo.CurrentCulture, `"$(Escape $resources[$m.Name])`", $args);")
    }
    [void]$strings.AppendLine('    }')
    [void]$strings.AppendLine('}')

    # ---- Error: invoke each method with markers to learn the exception it creates ----
    $modifier = if ($errorType.IsAbstract -and $errorType.IsSealed) { 'static partial class' } else { 'partial class' }
    [void]$errors.AppendLine("namespace $ns")
    [void]$errors.AppendLine('{')
    [void]$errors.AppendLine("    internal $modifier Error")
    [void]$errors.AppendLine('    {')
    foreach ($m in ($errorType.GetMethods($flags) | Where-Object { -not $_.IsSpecialName } | Sort-Object Name)) {
        # The one handwritten method (SqlClient\Error.cs) stays in its own file.
        if ($ns -eq 'System.Data.Linq.SqlClient' -and $m.Name -eq 'ExpressionNotSupportedForSqlServerVersion') { continue }
        $parameters = $m.GetParameters()
        $markers = @($parameters | ForEach-Object { "<<$($_.Position)>>" })
        $exception = $m.Invoke($null, [object[]]$markers)
        $type = $exception.GetType().FullName
        $params = ($parameters | ForEach-Object { "$(TypeName $_.ParameterType) $($_.Name)" }) -join ', '
        $args = ($parameters | ForEach-Object { $_.Name }) -join ', '

        $stringsMember = $stringsType.GetMember($m.Name, $flags)
        $expected = if ($resources.ContainsKey($m.Name)) { [string]::Format($resources[$m.Name], [object[]]$markers) } else { $null }
        $body =
            if ($exception -is [ArgumentNullException] -and $parameters.Count -eq 1 -and $exception.ParamName -eq $markers[0]) {
                "new ArgumentNullException($($parameters[0].Name))"
            } elseif ($exception -is [ArgumentOutOfRangeException] -and $parameters.Count -eq 1 -and $exception.ParamName -eq $markers[0]) {
                "new ArgumentOutOfRangeException($($parameters[0].Name))"
            } elseif ($stringsMember.Count -gt 0 -and $exception.Message -eq $expected) {
                if ($parameters.Count -gt 0) { "new $type(Strings.$($m.Name)($args))" } else { "new $type(Strings.$($m.Name))" }
            } elseif ($exception -is [ObjectDisposedException] -and $stringsMember.Count -gt 0 -and $exception.ObjectName -eq $expected) {
                # ObjectDisposedException(objectName): the text becomes the object's name, as the original does.
                if ($parameters.Count -gt 0) { "new $type(Strings.$($m.Name)($args))" } else { "new $type(Strings.$($m.Name))" }
            } elseif ($exception.Message -eq (New-Object $type).Message) {
                "new $type()"
            } else {
                throw "$ns.Error.$($m.Name): unexpected shape (message '$($exception.Message)')"
            }
        [void]$errors.AppendLine("        internal static Exception $($m.Name)($params) => $body;")
    }
    [void]$errors.AppendLine('    }')
    [void]$errors.AppendLine('}')
}

$strings.ToString() | Out-File (Join-Path $out 'Strings.generated.cs') -Encoding utf8
$errors.ToString() | Out-File (Join-Path $out 'Error.generated.cs') -Encoding utf8
"generated -> $out (Strings.generated.cs, Error.generated.cs)"
