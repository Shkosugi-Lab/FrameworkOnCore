# Writes casemap.h: the case of Windows' file names, as NTFS compares them (its upcase table: RtlUpcaseUnicodeChar),
# for each character of the Basic Multilingual Plane it changes. Runs on Windows.
#   .\experiments\wf4c\casefs\make-casemap.ps1
Add-Type -Namespace FocCase -Name Rtl -MemberDefinition '[System.Runtime.InteropServices.DllImport("ntdll.dll")] public static extern ushort RtlUpcaseUnicodeChar(ushort c);'
$pairs = New-Object System.Collections.Generic.List[string]
for ($c = 0; $c -le 0xFFFF; $c++) {
    if ($c -ge 0xD800 -and $c -le 0xDFFF) { continue }   # surrogates: halves of the characters outside the plane
    $upper = [int][FocCase.Rtl]::RtlUpcaseUnicodeChar([uint16]$c)
    if ($upper -ne $c) { $pairs.Add(('{{ 0x{0:X4}, 0x{1:X4} }}' -f $c, $upper)) }
}
$version = (Get-CimInstance Win32_OperatingSystem).Version
$text = "// The case of Windows' file names (NTFS's upcase table): each character of the Basic Multilingual Plane that`n" +
    "// RtlUpcaseUnicodeChar makes another, and that one, in order. Generated by casefs\make-casemap.ps1 on Windows $version.`n" +
    "// Characters outside the plane are compared as they are (Windows does too).`n" +
    "static const unsigned short upcase_table[][2] = {`n" + (($pairs | ForEach-Object { "    $_," }) -join "`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'casemap.h'), $text, (New-Object Text.UTF8Encoding $false))
"casemap.h: $($pairs.Count) characters (Windows $version)"
