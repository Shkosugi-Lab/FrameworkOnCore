using System.Collections.Immutable;
using System.Text;
using FrameworkOnCore.Analyzers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using CS = Microsoft.CodeAnalysis.CSharp;
using CSS = Microsoft.CodeAnalysis.CSharp.Syntax;
using VB = Microsoft.CodeAnalysis.VisualBasic;
using VBS = Microsoft.CodeAnalysis.VisualBasic.Syntax;

namespace WebFormsForCore.Compilers
{
	/// <summary>
	/// FrameworkOnCore: what the server compiles (the pages' code and data-binding expressions, App_Code, CodeFile pages)
	/// rewritten before it is compiled, as the converter rewrites the application's projects (FOC1008, FrameworkOnCore.Analyzers'
	/// FloatingTextAnalyzer, the same code): a double or float made text goes through System.Web.Util.FrameworkNumbers, which
	/// writes it as .NET Framework did (&lt;%#: String.Format("{0:c}", Item.UnitPrice) %&gt; of 22.5: ¥23, not .NET's ¥22).
	/// The sources are the compiler's command line's (the files ASP.NET generated for this compilation), written again
	/// where something changed. Off with the switch FrameworkOnCore.FloatingPointText false (the choice of .NET's text).
	/// </summary>
	static class FloatingTextRewriter
	{
		const string Numbers = "System.Web.Util.FrameworkNumbers.";

		public static void Rewrite(string[] arguments, bool visualBasic, string workingDirectory, string sdkDirectory)
		{
			if (AppContext.TryGetSwitch("FrameworkOnCore.FloatingPointText", out var on) && !on) return;
			try
			{
				CommandLineArguments parsed = visualBasic
					? VB.VisualBasicCommandLineParser.Default.Parse(arguments, workingDirectory, sdkDirectory)
					: CS.CSharpCommandLineParser.Default.Parse(arguments, workingDirectory, sdkDirectory);
				if (parsed.Errors.Any(e => e.Severity == DiagnosticSeverity.Error)) return;
				var trees = parsed.SourceFiles
					.Where(f => File.Exists(f.Path))
					.Select(f => visualBasic
						? VB.VisualBasicSyntaxTree.ParseText(File.ReadAllText(f.Path), (VB.VisualBasicParseOptions)parsed.ParseOptions, f.Path)
						: CS.CSharpSyntaxTree.ParseText(File.ReadAllText(f.Path), (CS.CSharpParseOptions)parsed.ParseOptions, f.Path))
					.ToList();
				if (trees.Count == 0) return;
				var references = parsed.MetadataReferences
					.Select(r => ResolvedPath(r.Reference, parsed.ReferencePaths, workingDirectory))
					.Where(p => p != null)
					.Select(p => (MetadataReference)MetadataReference.CreateFromFile(p))
					.ToList();
				Compilation compilation = visualBasic
					? VB.VisualBasicCompilation.Create("rewrite", trees, references, (VB.VisualBasicCompilationOptions)parsed.CompilationOptions)
					: CS.CSharpCompilation.Create("rewrite", trees, references, (CS.CSharpCompilationOptions)parsed.CompilationOptions);
				// ASP.NET's files say <auto-generated>: the code in them is the page's (its expressions, its script), analyzed too.
				var diagnostics = compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new FloatingTextAnalyzer(generatedCode: true)))
					.GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();
				Log($"{trees.Count} file(s), {references.Count}/{parsed.MetadataReferences.Length} reference(s), {diagnostics.Length} place(s); errors: " +
					string.Join(" | ", compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).Take(3)));
				foreach (var file in diagnostics.Where(d => d.Location.IsInSource).GroupBy(d => d.Location.SourceTree))
				{
					var root = file.Key.GetRoot();
					var edits = new Dictionary<SyntaxNode, string>();
					foreach (var d in file)
					{
						var node = root.FindNode(d.Location.SourceSpan, getInnermostNodeForTie: true);
						if (node.Span != d.Location.SourceSpan) continue;
						var tag = System.Text.RegularExpressions.Regex.Match(d.GetMessage(), @",(?<tag>\w+)\]$").Groups["tag"].Value;
						if (tag.Length > 0) edits[node] = tag;
					}
					if (edits.Count == 0) continue;
					var rewritten = root.ReplaceNodes(edits.Keys, (original, inner) => Edit(original, inner, edits[original], visualBasic) ?? inner);
					File.WriteAllText(file.Key.FilePath, rewritten.ToFullString(), new UTF8Encoding(true));
				}
			}
			catch (Exception ex)
			{
				// The sources compile as they are: what the server writes of a double is then .NET's.
				Log("not rewritten: " + ex);
			}
		}

		// FOC_REWRITE_LOG: a file the rewriter tells what it did (and why not).
		static void Log(string line)
		{
			var log = Environment.GetEnvironmentVariable("FOC_REWRITE_LOG");
			if (!string.IsNullOrEmpty(log)) try { File.AppendAllText(log, DateTime.Now.ToString("s") + " " + line + Environment.NewLine); } catch (IOException) { }
		}

		static string ResolvedPath(string reference, ImmutableArray<string> paths, string workingDirectory)
		{
			if (Path.IsPathRooted(reference)) return File.Exists(reference) ? reference : null;
			foreach (var directory in paths.Prepend(workingDirectory))
			{
				var candidate = Path.Combine(directory, reference);
				if (File.Exists(candidate)) return candidate;
			}
			return null;
		}

		static string Global(bool visualBasic) => (visualBasic ? "Global." : "global::") + Numbers;

		static SyntaxNode Edit(SyntaxNode original, SyntaxNode node, string tag, bool visualBasic)
		{
			string text = null;
			switch (tag)
			{
				case "text":
				case "formattable":
				case "texts":
					text = Global(visualBasic) + (tag == "text" ? "Text" : tag == "formattable" ? "Formattable" : "Texts") + "(" + node.WithoutTrivia().ToString() + ")";
					break;
				case "call_instance":
					if (Split(node, out var receiver, out var arguments) && receiver != null)
						text = Global(visualBasic) + "ToString(" + string.Join(", ", new[] { receiver }.Concat(arguments)) + ")";
					break;
				case "vbparse":
				case "vbparse_single":
					text = Global(visualBasic) + (tag == "vbparse" ? "VisualBasicToDouble" : "VisualBasicToSingle") + "(" + node.WithoutTrivia().ToString() + ")";
					break;
				case "convert":
					if (Split(node, out _, out var convertArguments))
						text = Global(visualBasic) + "ConvertToString(" + string.Join(", ", convertArguments) + ")";
					break;
			}
			if (text == null) return null;
			// In a C# interpolation's hole "global::" would start the hole's format.
			if (!visualBasic && original.Parent is CSS.InterpolationSyntax) text = "(" + text + ")";
			var expression = visualBasic ? (SyntaxNode)VB.SyntaxFactory.ParseExpression(text) : CS.SyntaxFactory.ParseExpression(text);
			return expression.WithTriviaFrom(node);
		}

		static bool Split(SyntaxNode node, out string receiver, out List<string> arguments)
		{
			(receiver, arguments) = (null, new List<string>());
			switch (node)
			{
				case CSS.InvocationExpressionSyntax { Expression: CSS.MemberAccessExpressionSyntax access } invocation:
					receiver = access.Expression.WithoutTrivia().ToString();
					arguments = invocation.ArgumentList.Arguments.Select(a => a.WithoutTrivia().ToString()).ToList();
					return true;
				case VBS.InvocationExpressionSyntax { Expression: VBS.MemberAccessExpressionSyntax access } invocation when access.Expression != null:
					receiver = access.Expression.WithoutTrivia().ToString();
					arguments = invocation.ArgumentList?.Arguments.Select(a => a.WithoutTrivia().ToString()).ToList() ?? new List<string>();
					return true;
				default:
					return false;
			}
		}
	}
}
