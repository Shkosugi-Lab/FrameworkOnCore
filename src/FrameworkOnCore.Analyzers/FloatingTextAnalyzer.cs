using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace FrameworkOnCore.Analyzers;

/// <summary>
/// Where the application makes text of a double or a float, which .NET Core 3.0 writes otherwise than .NET Framework
/// ("0.30000000000000004" for 0.1 + 0.2, "-0", 2.675 as "N2" "2.67"; FrameworkOnCore.Compat's FrameworkNumbers writes it
/// as .NET Framework did). FOC1008 at the expression, its tag what the converter writes (C# and Visual Basic alike):
/// - call_instance: x.ToString(...) of a double, a float, or a value typed object (a DataRow's field: a boxed double is
///   one): FrameworkNumbers.ToString(x, ...);
/// - convert: Convert.ToString(x[, provider]) of one: FrameworkNumbers.ConvertToString(x[, provider]);
/// - text: x joined to text (string concatenation, VB's conversion to String, StringBuilder.Append, TextWriter.Write,
///   String.Concat, String.Join's items, Response.Write): FrameworkNumbers.Text(x);
/// - formattable: x a format item formats (string.Format's arguments, an interpolation's hole):
///   FrameworkNumbers.Formattable(x), which applies the item's format as .NET Framework did;
/// - texts: the doubles String.Join joins: FrameworkNumbers.Texts(x).
/// Not in an expression tree (a query provider translates ToString; it does not know FrameworkNumbers).
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp, LanguageNames.VisualBasic)]
public sealed class FloatingTextAnalyzer : DiagnosticAnalyzer
{
    public const string Id = "FOC1008";

    static readonly DiagnosticDescriptor Rule = new(Id, "A double or float made text",
        "A double or float made text, which .NET writes otherwise than .NET Framework: {0}", "FrameworkOnCore", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => ImmutableArray.Create(Rule);

    // Generated code too: FrameworkOnCore's System.Web runs it on what the server compiles, ASP.NET's generated files
    // (<auto-generated>) holding the pages' code and expressions. The build's (the converter's) leaves designers' files.
    readonly bool generatedCode;

    public FloatingTextAnalyzer() : this(false) { }

    public FloatingTextAnalyzer(bool generatedCode) => this.generatedCode = generatedCode;

    public override void Initialize(AnalysisContext context)
    {
        context.EnableConcurrentExecution();
        context.ConfigureGeneratedCodeAnalysis(generatedCode ? GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics : GeneratedCodeAnalysisFlags.None);
        context.RegisterOperationAction(Invocation, OperationKind.Invocation);
        context.RegisterOperationAction(Binary, OperationKind.Binary, OperationKind.CompoundAssignment);
        context.RegisterOperationAction(Interpolation, OperationKind.Interpolation);
        context.RegisterOperationAction(Conversion, OperationKind.Conversion);
    }

    // A double or a float, or one of them nullable.
    static bool IsFloating(ITypeSymbol? type)
    {
        if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable) type = nullable.TypeArguments[0];
        return type?.SpecialType is SpecialType.System_Double or SpecialType.System_Single;
    }

    static bool IsObject(ITypeSymbol? type) => type?.SpecialType == SpecialType.System_Object;

    // What a value is before it was boxed (to object, to a params array's item): the double, or the object it was.
    static IOperation Unboxed(IOperation value) =>
        value is IConversionOperation { IsImplicit: true } conversion && IsObject(conversion.Type) ? conversion.Operand : value;


    // A value that may hold a double: one, or an object (not a literal null, not this/base).
    static bool MayBeFloating(IOperation value)
    {
        var inner = Unboxed(value);
        if (IsFloating(inner.Type)) return true;
        return IsObject(inner.Type) && inner is not (IInstanceReferenceOperation or ILiteralOperation) && inner.ConstantValue is not { HasValue: true };
    }

    static void Report(OperationAnalysisContext context, IOperation at, string what, string tag)
    {
        if (at.Syntax.Span.Length == 0 || SpanInExpressionAnalyzer.InExpressionTree(at)) return;
        context.ReportDiagnostic(Located.Create(Rule, at.Syntax, what, tag));
    }

    static string Name(ITypeSymbol type) => Located.FullName(type);

    static void Invocation(OperationAnalysisContext context)
    {
        var invocation = (IInvocationOperation)context.Operation;
        var method = invocation.TargetMethod;
        var type = method.ContainingType;
        if (type == null) return;

        // x.ToString(...)
        if (method.Name == "ToString" && invocation.Instance is { } instance && instance is not IInstanceReferenceOperation)
        {
            if (type.SpecialType is SpecialType.System_Double or SpecialType.System_Single)
            {
                Report(context, invocation, $"{Name(type)}.ToString", "call_instance");
                return;
            }
            if (type.SpecialType == SpecialType.System_Object && method.Parameters.Length == 0 && MayBeFloating(instance))
            {
                Report(context, invocation, "object.ToString", "call_instance");
                return;
            }
        }

        var typeName = Name(type);
        // Convert.ToString(x) and Convert.ToString(x, provider).
        if (typeName == "System.Convert" && method.Name == "ToString" && method.Parameters.Length is 1 or 2 &&
            (method.Parameters.Length == 1 || method.Parameters[1].Type.Name == "IFormatProvider") &&
            invocation.Arguments.FirstOrDefault(a => a.Parameter?.Ordinal == 0) is { } first && MayBeFloating(first.Value))
        {
            Report(context, invocation, "Convert.ToString", "convert");
            return;
        }

        // HttpUtility.HtmlEncode(object) of a double (<%: d %>): an object of another type keeps its own (an IHtmlString).
        if (typeName == "System.Web.HttpUtility" && method.Name == "HtmlEncode" && method.Parameters.Length == 1 && IsObject(method.Parameters[0].Type) &&
            invocation.Arguments.FirstOrDefault()?.Value is { } encoded && IsFloating(Unboxed(encoded).Type))
        {
            Report(context, Unboxed(encoded), "HttpUtility.HtmlEncode's argument", "text");
            return;
        }

        var writes = method.Name is "Write" or "WriteLine" && (DerivesFrom(type, "System.IO.TextWriter") || typeName is "System.Console" or "System.Web.HttpResponse" or "System.Web.HttpResponseBase" or "System.Web.HttpResponseWrapper")
            || method.Name is "Append" or "Insert" or "AppendLine" && typeName == "System.Text.StringBuilder";
        // Composite formatting (its arguments formatted by the format's items), .NET's own: another method taking a
        // format and objects may keep them (an argument cast back to double).
        var format = method.Parameters.Any(p => p.Name == "format" && p.Type.SpecialType == SpecialType.System_String) &&
            (typeName is "System.String" or "System.Text.StringBuilder" or "System.Console" or "System.Diagnostics.Debug" or "System.Diagnostics.Trace"
             || DerivesFrom(type, "System.IO.TextWriter"));
        var concat = typeName == "System.String" && method.Name is "Concat" or "Join";
        if (!writes && !format && !concat) return;

        foreach (var argument in invocation.Arguments)
        {
            if (argument.Parameter == null || argument.ArgumentKind == ArgumentKind.DefaultValue) continue;
            var parameterType = argument.Parameter.Type;
            // String.Join<T>(separator, IEnumerable<T>) of doubles.
            if (concat && method.Name == "Join" && method.IsGenericMethod && IsFloating(method.TypeArguments[0]) &&
                parameterType is INamedTypeSymbol { Name: "IEnumerable" })
            {
                Report(context, argument.Value, "String.Join", "texts");
                continue;
            }
            var values = argument.ArgumentKind == ArgumentKind.ParamArray && argument.Value is IArrayCreationOperation { Initializer: { } items }
                ? items.ElementValues.AsEnumerable()
                : new[] { argument.Value };
            foreach (var value in values)
            {
                var inner = Unboxed(value);
                if (format && argument.Parameter.Name != "format" && (argument.ArgumentKind == ArgumentKind.ParamArray || IsObject(parameterType)) && MayBeFloating(value))
                    Report(context, inner, $"{typeName}.{method.Name}'s argument", "formattable");
                else if (!format && (writes || concat) && (IsFloating(parameterType) || IsObject(parameterType) || argument.ArgumentKind == ArgumentKind.ParamArray) && MayBeFloating(value))
                    Report(context, inner, $"{typeName}.{method.Name}'s argument", "text");
            }
        }
    }

    static bool DerivesFrom(INamedTypeSymbol? type, string name)
    {
        for (; type != null; type = type.BaseType)
            if (Located.FullName(type) == name) return true;
        return false;
    }

    // C#'s string concatenation (a + b, s += x): an operand that is a double, or an object (boxed or not).
    static void Binary(OperationAnalysisContext context)
    {
        IOperation left, right;
        switch (context.Operation)
        {
            case IBinaryOperation { OperatorKind: BinaryOperatorKind.Add, Type.SpecialType: SpecialType.System_String } binary
                when binary.Language == LanguageNames.CSharp:
                (left, right) = (binary.LeftOperand, binary.RightOperand);
                break;
            case ICompoundAssignmentOperation { OperatorKind: BinaryOperatorKind.Add, Target.Type.SpecialType: SpecialType.System_String } compound
                when compound.Language == LanguageNames.CSharp:
                (left, right) = (null!, compound.Value);
                break;
            // Visual Basic's & (s &= x too): its operands converted to String, or an Object's late bound.
            case IBinaryOperation { OperatorKind: BinaryOperatorKind.Concatenate } concatenation:
                (left, right) = (concatenation.LeftOperand, concatenation.RightOperand);
                break;
            case ICompoundAssignmentOperation { OperatorKind: BinaryOperatorKind.Concatenate } concatenated:
                (left, right) = (null!, concatenated.Value);
                break;
            default:
                return;
        }
        foreach (var operand in new[] { left, right })
        {
            if (operand == null) continue;
            // What was converted to String (Visual Basic) or boxed (C#), as it was.
            var inner = operand is IConversionOperation { IsImplicit: true } conversion && conversion.Type?.SpecialType is SpecialType.System_String or SpecialType.System_Object
                ? conversion.Operand : operand;
            if (!IsFloating(inner.Type) && !(IsObject(inner.Type) && MayBeFloating(inner))) continue;
            Report(context, inner, "string concatenation", "text");
        }
    }

    // An interpolation's hole ($"{x:N2}"), C# and Visual Basic.
    static void Interpolation(OperationAnalysisContext context)
    {
        var interpolation = (IInterpolationOperation)context.Operation;
        if (!MayBeFloating(interpolation.Expression)) return;
        Report(context, Unboxed(interpolation.Expression), "interpolation", "formattable");
    }

    // Visual Basic's conversion of a double to String (CStr(x), a String assigned a Double); a concatenation's operands
    // are its own (Binary). And of a String to a Double or Single (CDbl(s), a Double assigned a String): too large a
    // number is infinity on .NET, an OverflowException on .NET Framework (vbparse: the string, as
    // FrameworkOnCore.VisualBasicText.ToDouble's).
    static void Conversion(OperationAnalysisContext context)
    {
        var conversion = (IConversionOperation)context.Operation;
        if (conversion.Language != LanguageNames.VisualBasic) return;
        if (conversion.Operand.Type?.SpecialType == SpecialType.System_String && conversion.Type?.SpecialType is SpecialType.System_Double or SpecialType.System_Single)
        {
            Report(context, conversion.Operand, "conversion of a String to a " + conversion.Type.Name, conversion.Type.SpecialType == SpecialType.System_Double ? "vbparse" : "vbparse_single");
            return;
        }
        if (conversion.Type?.SpecialType != SpecialType.System_String) return;
        if (conversion.IsImplicit && conversion.Parent is IBinaryOperation { OperatorKind: BinaryOperatorKind.Concatenate } or ICompoundAssignmentOperation { OperatorKind: BinaryOperatorKind.Concatenate }) return;
        if (!IsFloating(conversion.Operand.Type)) return;
        Report(context, conversion.Operand, "conversion to String", "text");
    }
}
