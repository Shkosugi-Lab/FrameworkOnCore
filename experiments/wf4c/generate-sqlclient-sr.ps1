# Generates Core\SR.generated.cs of the System.Data.SqlClient port (FrameworkOnCore.Runtime\src\WebFormsForCore.Data.SqlClient):
# the SR class's resource properties, which dotnet/maintenance-packages' build (Arcade's GenerateResourcesSource) made from
# Resources\Strings.resx. One property per string (its value read from the embedded resources, as the original's),
# the ResourceManager over the resources the project embeds (System.Data.SqlClient.Strings.resources).
# Rerun when Strings.resx changes; the output is committed with the port.
$ErrorActionPreference = 'Stop'
$root = Join-Path $PSScriptRoot '..\..\FrameworkOnCore.Runtime\src\WebFormsForCore.Data.SqlClient'
[xml]$resx = Get-Content (Join-Path $root 'Resources\Strings.resx') -Raw -Encoding UTF8
$names = $resx.root.data | Where-Object { -not $_.type } | ForEach-Object { $_.name } | Sort-Object -Unique
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//     Generated by experiments/wf4c/generate-sqlclient-sr.ps1 from Resources\Strings.resx (what dotnet/maintenance-packages'' build')
[void]$sb.AppendLine('//     generated for System.Data.SqlClient). Do not edit.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('#nullable enable')
[void]$sb.AppendLine('namespace System')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    internal static partial class SR')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        private static global::System.Resources.ResourceManager? s_resourceManager;')
[void]$sb.AppendLine('        internal static global::System.Resources.ResourceManager ResourceManager =>')
[void]$sb.AppendLine('            s_resourceManager ??= new global::System.Resources.ResourceManager("System.Data.SqlClient.Strings", typeof(SR).Assembly);')
foreach ($name in $names) {
    [void]$sb.AppendLine("        internal static string @$name => GetResourceString(""$name"");")
}
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
New-Item -ItemType Directory (Join-Path $root 'Core') -Force | Out-Null
[IO.File]::WriteAllText((Join-Path $root 'Core\SR.generated.cs'), $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"generated $($names.Count) resource properties -> $root\Core\SR.generated.cs"
