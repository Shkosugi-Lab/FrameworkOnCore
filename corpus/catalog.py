"""The corpus's catalog of aspects (corpus/README.md): every snapshot of every probe's parity scenario is an aspect the
corpus checks, as the original answered it on IIS; the host's generated suites (the attack and settings tests) are aspects
of their own. Writes corpus/ASPECTS.md, and with --check fails (exit 1) when the corpus is not whole:

- a probe of corpus/probes.json without its folder, project, parity scenario or golden data;
- a snapshot of a scenario that the golden data has not (recorded before it was added: record the probe again on IIS);
- a snapshot name given twice in a probe;
- a sample with a parity scenario that corpus/probes.json does not list (a probe added but not to the corpus).

    python corpus/catalog.py [--check]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(ROOT, "corpus")
SAMPLES = os.path.join(ROOT, "samples")


def load(path):
    with open(path, encoding="utf-8-sig") as f:
        return json.load(f)


def main():
    check = "--check" in sys.argv[1:]
    problems = []
    probes = load(os.path.join(CORPUS, "probes.json"))["probes"]
    listed = {p["name"] for p in probes}
    for name in sorted(os.listdir(SAMPLES)):
        if os.path.exists(os.path.join(SAMPLES, name, "parity-scenario.json")) and name not in listed:
            problems.append(f"{name}: a sample with a parity scenario not in corpus/probes.json")
    sections = []
    total = 0
    for probe in probes:
        name = probe["name"]
        folder = os.path.join(SAMPLES, name)
        scenario_file = os.path.join(folder, "parity-scenario.json")
        golden_file = os.path.join(folder, "golden-webforms.json")
        missing = [p for p in (folder, os.path.join(folder, probe.get("project") or "?"), scenario_file, golden_file) if not os.path.exists(p)]
        if missing:
            problems.append(f"{name}: missing " + ", ".join(os.path.relpath(m, ROOT) for m in missing))
            continue
        scenario = load(scenario_file)
        golden = load(golden_file)
        recorded = {s.get("Name") for s in golden.get("Snapshots", [])}
        snapshots = [s["name"] for s in scenario.get("steps", []) if isinstance(s, dict) and s.get("action") == "snapshot"]
        seen = set()
        for snapshot in snapshots:
            if snapshot in seen:
                problems.append(f"{name}: the snapshot {snapshot!r} twice")
            seen.add(snapshot)
            if snapshot not in recorded:
                problems.append(f"{name}: the snapshot {snapshot!r} has no IIS answer (record the probe again: corpus/README.md)")
        total += len(snapshots)
        comment = scenario.get("_comment", "").strip()
        sections.append((name, probe.get("project"), comment, snapshots, len(golden.get("Links") or [])))
    lines = [
        "# The corpus's aspects",
        "",
        "Generated by `corpus/catalog.py` from the probes' parity scenarios (samples/&lt;probe&gt;/parity-scenario.json); do not edit.",
        f"{len(sections)} probes, {total} snapshots (each compared with what the original answered on IIS), and the host's generated suites.",
        "",
        "## The host's generated suites",
        "",
        "| suite | what | where |",
        "|---|---|---|",
        "| IIS's settings | every setting of IIS's configuration schema a site's web.config may have, one at a time, 47 probes each | tests/RuntimeUnitTests/Security/iis-golden/IIS-SETTINGS.md |",
        "| Attacks | paths, request filtering, Windows' names, limits, headers, bodies, redirects, combinations and pairs, against IIS 10 | tests/RuntimeUnitTests/Security/iis-golden/iis.json |",
        "| IIS's pipeline | which module of IIS's answers each attack case (failed request tracing) | tests/RuntimeUnitTests/Security/iis-golden/IIS-PIPELINE.md |",
        "",
        "## The probes",
        "",
    ]
    for name, project, comment, snapshots, links in sections:
        lines.append(f"### {name} ({len(snapshots)} snapshots{f', {links} links' if links else ''})")
        lines.append("")
        if comment:
            lines.append(comment)
            lines.append("")
        lines.append(", ".join(f"`{s}`" for s in snapshots))
        lines.append("")
    with open(os.path.join(CORPUS, "ASPECTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    for problem in problems:
        print(problem)
    print(f"{len(sections)} probes, {total} snapshots; {len(problems)} problems")
    return 1 if check and problems else 0


if __name__ == "__main__":
    sys.exit(main())
