# Generates Core\Unix\*.generated.cs of the System.Drawing.Common port (FrameworkOnCore.Runtime\src\WebFormsForCore.Drawing.Common):
# the Unix build's GDI+ flat API with a choice of implementation, libgdiplus (the default) or SkiaSharp (Core\Unix\Skia).
#   GdiplusNative.generated.cs, GdiplusNative.Unix.generated.cs: System\Drawing\GdiplusNative.cs and GdiplusNative.Unix.cs as
#     they are, each DllImport replaced by a method of the same signature that calls the chosen implementation (GdipBackend).
#     The Unix build compiles these instead of the two files.
#   Libgdiplus.generated.cs: the DllImports, as they were, in Gdip.Libgdiplus.
#   SkiaGdip.Stubs.generated.cs: SkiaGdip's functions not written yet (in Core\Unix\Skia), returning NotImplemented.
# The two files' #if WebFormsForCore are resolved here (the port defines it); any other directive stops the script.
# Rerun when the two files change, or when a SkiaGdip function is written or removed; the output is committed with the port.
$ErrorActionPreference = 'Stop'
$root = Join-Path $PSScriptRoot '..\..\FrameworkOnCore.Runtime\src\WebFormsForCore.Drawing.Common'
$outDir = Join-Path $root 'Core\Unix'
$skiaDir = Join-Path $outDir 'Skia'
$utf8 = New-Object Text.UTF8Encoding($true)

function Resolve-Directives([string[]]$lines, [string]$file) {
    # Keeps the lines of the active branches (WebFormsForCore defined).
    $out = New-Object Collections.Generic.List[string]
    $stack = New-Object Collections.Generic.Stack[bool]
    $active = $true
    foreach ($l in $lines) {
        $t = $l.Trim()
        if ($t -match '^#if\s+(!?)WebFormsForCore\b') {
            $stack.Push($active); $active = $active -and ($Matches[1] -ne '!'); continue
        }
        if ($t -match '^#else\b') {
            $outer = $stack.Peek(); $active = $outer -and -not $active; continue
        }
        if ($t -match '^#endif\b') { $active = $stack.Pop(); continue }
        if ($t -match '^#') { throw "${file}: directive not handled: $t" }
        if ($active) { $out.Add($l) }
    }
    if ($stack.Count) { throw "${file}: #if without #endif" }
    return ,$out.ToArray()
}

function Split-Parameters([string]$text) {
    $text = [regex]::Replace($text, '\[[A-Za-z][^\]]*\]\s*', '')   # [In], [Out], [MarshalAs(...)]: the marshaller's, not the method's (not an array's [])
    $list = @()
    foreach ($p in ($text -split ',')) {
        $p = ($p -replace '\s+', ' ').Trim()
        if (-not $p) { continue }
        if ($p -notmatch '^(?:(?<mod>ref|out|in) )?(?<type>.+?) (?<name>@?\w+)$') { throw "parameter not understood: $p" }
        $list += [pscustomobject]@{ Mod = $Matches.mod; Type = $Matches.type; Name = $Matches.name }
    }
    return ,$list
}

function Get-Key([string]$name, $params) {
    $name + '(' + (($params | ForEach-Object { ("$($_.Mod) $($_.Type)").Trim() -replace '\s+', '' }) -join ',') + ')'
}

$functions = New-Object Collections.Generic.List[object]
$externs = New-Object Collections.Generic.List[string]
$usings = New-Object Collections.Generic.SortedSet[string]

foreach ($name in 'GdiplusNative.cs', 'GdiplusNative.Unix.cs') {
    $source = Join-Path $root "System\Drawing\$name"
    $lines = Resolve-Directives ([IO.File]::ReadAllLines($source)) $name
    $out = New-Object Collections.Generic.List[string]
    $out.Add('// <auto-generated>')
    $out.Add("//     Generated by experiments/wf4c/generate-gdip-dispatch.ps1 from System\Drawing\$name (the Unix build's): the file")
    $out.Add('//     with each DllImport a call of the chosen implementation (GdipBackend; the imports are Gdip.Libgdiplus). Do not edit.')
    $out.Add('// </auto-generated>')
    $out.Add('#nullable enable')
    $i = 0
    while ($i -lt $lines.Length) {
        $l = $lines[$i]
        if ($l -match '^using [\w\.]+;') { [void]$usings.Add($l.Trim()) }
        if ($l -notmatch '^\s*\[DllImport\(') { $out.Add($l); $i++; continue }
        $indent = ($l -replace '^(\s*).*', '$1')
        $block = New-Object Collections.Generic.List[string]
        while ($true) {
            $block.Add($lines[$i])
            $code = ($lines[$i] -replace '//.*$', '').TrimEnd()
            $i++
            if ($code.EndsWith(';')) { break }
        }
        foreach ($b in $block) { $externs.Add('    ' + $b) }
        $decl = (($block | Where-Object { $_ -notmatch '^\s*\[DllImport\(' } | ForEach-Object { $_ -replace '//.*$', '' }) -join ' ')
        if ($decl -notmatch '^\s*internal static extern (?:unsafe )?(?<ret>[\w\.\?\*]+) (?<fn>\w+)\s*\((?<params>.*)\)\s*;\s*$') { throw "${name}: not understood: $decl" }
        $ret = $Matches.ret; $fn = $Matches.fn
        $params = Split-Parameters $Matches.params
        $sig = ($params | ForEach-Object { ("$($_.Mod) $($_.Type) $($_.Name)").Trim() }) -join ', '
        $callArgs = ($params | ForEach-Object { ("$($_.Mod) $($_.Name)").Trim() }) -join ', '
        $out.Add("${indent}internal static $ret $fn($sig)")
        $out.Add("${indent}{")
        $out.Add("${indent}    if (GdipBackend.Tracing) GdipBackend.Called(`"$fn`");")
        if ($ret -eq 'void') {
            $out.Add("${indent}    if (GdipBackend.Skia) SkiaGdip.$fn($callArgs); else Libgdiplus.$fn($callArgs);")
        } else {
            $out.Add("${indent}    return GdipBackend.Skia ? SkiaGdip.$fn($callArgs) : Libgdiplus.$fn($callArgs);")
        }
        $out.Add("${indent}}")
        $functions.Add([pscustomobject]@{ Name = $fn; Ret = $ret; Params = $params; Sig = $sig; Key = (Get-Key $fn $params) })
    }
    [IO.File]::WriteAllLines((Join-Path $outDir ($name -replace '\.cs$', '.generated.cs')), $out, $utf8)
}

$usingLines = @($usings)

# Libgdiplus.generated.cs
$lib = New-Object Collections.Generic.List[string]
$lib.Add('// <auto-generated>')
$lib.Add('//     Generated by experiments/wf4c/generate-gdip-dispatch.ps1: the DllImports of System\Drawing\GdiplusNative.cs and')
$lib.Add('//     GdiplusNative.Unix.cs (the Unix build''s), as they are, libgdiplus'' functions. Do not edit.')
$lib.Add('// </auto-generated>')
$lib.Add('#nullable enable')
$lib.AddRange([string[]]$usingLines)
$lib.Add('')
$lib.Add('namespace System.Drawing')
$lib.Add('{')
$lib.Add('    internal static partial class SafeNativeMethods')
$lib.Add('    {')
$lib.Add('        internal static unsafe partial class Gdip')
$lib.Add('        {')
$lib.Add('            internal static unsafe class Libgdiplus')
$lib.Add('            {')
$lib.AddRange($externs)
$lib.Add('            }')
$lib.Add('        }')
$lib.Add('    }')
$lib.Add('}')
[IO.File]::WriteAllLines((Join-Path $outDir 'Libgdiplus.generated.cs'), $lib, $utf8)

# SkiaGdip.Stubs.generated.cs: the functions Core\Unix\Skia does not have.
$written = New-Object Collections.Generic.HashSet[string]
if (Test-Path $skiaDir) {
    foreach ($f in Get-ChildItem $skiaDir -Filter *.cs -Recurse | Where-Object { $_.Name -notlike '*.generated.cs' }) {
        $text = [IO.File]::ReadAllText($f.FullName)
        foreach ($m in [regex]::Matches($text, 'internal static (?:unsafe )?(?<ret>[\w\.\?\*]+) (?<fn>Gdip\w+|GdiplusStartup|GdiplusShutdown)\s*\((?<params>[^)]*)\)')) {
            [void]$written.Add((Get-Key $m.Groups['fn'].Value (Split-Parameters $m.Groups['params'].Value)))
        }
    }
}
$stub = New-Object Collections.Generic.List[string]
$stub.Add('// <auto-generated>')
$stub.Add('//     Generated by experiments/wf4c/generate-gdip-dispatch.ps1: the GDI+ functions SkiaGdip does not have yet (Core\Unix\Skia');
$stub.Add('//     has the others). Each returns NotImplemented, which the caller throws as NotImplementedException. Do not edit.')
$stub.Add('// </auto-generated>')
$stub.Add('#nullable enable')
$stub.AddRange([string[]]$usingLines)
$stub.Add('')
$stub.Add('namespace System.Drawing')
$stub.Add('{')
$stub.Add('    internal static partial class SafeNativeMethods')
$stub.Add('    {')
$stub.Add('        internal static unsafe partial class SkiaGdip')
$stub.Add('        {')
$stubbed = 0
foreach ($fn in $functions) {
    if ($written.Contains($fn.Key)) { continue }
    $stubbed++
    $stub.Add("            internal static $($fn.Ret) $($fn.Name)($($fn.Sig))")
    $stub.Add('            {')
    foreach ($p in $fn.Params | Where-Object { $_.Mod -eq 'out' }) { $stub.Add("                $($p.Name) = default;") }
    switch ($fn.Ret) {
        'void' { }
        'int' { $stub.Add('                return Gdip.NotImplemented;') }
        default { $stub.Add('                return default;') }
    }
    $stub.Add('            }')
}
$stub.Add('        }')
$stub.Add('    }')
$stub.Add('}')
[IO.File]::WriteAllLines((Join-Path $outDir 'SkiaGdip.Stubs.generated.cs'), $stub, $utf8)

"functions: $($functions.Count); in SkiaGdip: $($functions.Count - $stubbed); stubs: $stubbed"
